const dicts = { en, sw } as const;

export function translate(lang: "en" | "sw", key: MsgKey): string {
  return dicts[lang][key] ?? en[key];
}

/** `const t = useT(); t("nav.dashboard")` or `t("dash.billedTo", { n: 3 })` */
export function useT() {
  const [{ lang }] = useSettings();
  return useCallback(
    (key: MsgKey, vars?: Record<string, string | number>) => {
      let text = translate(lang, key);
      if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
      return text;
    },
    [lang],
  );
}

